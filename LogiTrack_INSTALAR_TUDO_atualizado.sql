create or replace function public.criar_pedido(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id     bigint;
    v_novas  int;
    v_usadas int;
    v_total  int;
begin
    perform public._exigir_operador();

    if coalesce(btrim(p ->> 'numero'), '') = '' then
        raise exception 'O número do pedido é obrigatório.' using errcode = '23502';
    end if;
    if coalesce(btrim(p ->> 'cliente'), '') = '' then
        raise exception 'O cliente é obrigatório.' using errcode = '23502';
    end if;

    -- compatibilidade: se vier só "cintas", entra como nova
    v_total  := coalesce((p ->> 'cintas')::int, 4);
    v_novas  := coalesce((p ->> 'cintasNovas')::int,  v_total);
    v_usadas := coalesce((p ->> 'cintasUsadas')::int, 0);

    if v_novas = 0 and v_usadas = 0 and p ? 'cintasNovas' then
        v_total := 0;
    end if;

    insert into public.pedidos (
        id, numero, cliente, cidade, uf, endereco, veiculo, placa,
        motorista, data, horario, cavaletes, lonas, forros,
        cintas, cintas_novas, cintas_usadas,
        lacres_lona, lacres_forro, entregue, data_entrega,
        coleta_cavalete_pendente, coleta_lona_pendente,
        quem_coletou_cavalete, quem_coletou_lona
    ) values (
        coalesce(nullif(p ->> 'id', '')::bigint,
                 nextval(pg_get_serial_sequence('public.pedidos', 'id'))),
        btrim(p ->> 'numero'),
        btrim(p ->> 'cliente'),
        coalesce(nullif(btrim(p ->> 'cidade'), ''), '---'),
        upper(coalesce(nullif(btrim(p ->> 'uf'), ''), 'SP')),
        nullif(btrim(p ->> 'endereco'), ''),
        coalesce(nullif(p ->> 'veiculo', ''), 'BITRUCK'),
        upper(coalesce(nullif(btrim(p ->> 'placa'), ''), '---')),
        coalesce(nullif(btrim(p ->> 'motorista'), ''), '---'),
        coalesce(public._para_data(p ->> 'data'), current_date),
        public._para_hora(p ->> 'horario'),
        coalesce((p ->> 'cavaletes')::int, 1),
        coalesce((p ->> 'lonas')::int, 1),
        coalesce((p ->> 'forros')::int, 1),
        v_novas + v_usadas,
        v_novas,
        v_usadas,
        public._para_text_array(p -> 'lacresLona'),
        public._para_text_array(p -> 'lacresForro'),
        coalesce((p ->> 'entregue')::boolean, false),
        public._para_data(p ->> 'dataEntrega'),
        coalesce((p ->> 'coletaCavaletePendente')::boolean, true),
        coalesce((p ->> 'coletaLonaPendente')::boolean, true),
        nullif(btrim(p ->> 'quemColetouCavalete'), ''),
        nullif(btrim(p ->> 'quemColetouLona'), '')
    )
    returning id into v_id;

    return v_id;
end;
$$;

create or replace function public.importar_pedidos(p_lista jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_item    jsonb;
    v_total   int := 0;
    v_erros   jsonb := '[]'::jsonb;
    v_ordem   int := 0;
begin
    perform public._exigir_operador();

    if jsonb_typeof(p_lista) <> 'array' then
        raise exception 'A importação espera uma lista de pedidos.' using errcode = '22023';
    end if;

    for v_item in select * from jsonb_array_elements(p_lista)
    loop
        v_ordem := v_ordem + 1;
        begin
            perform public.criar_pedido(v_item);
            v_total := v_total + 1;
        exception when others then
            v_erros := v_erros || jsonb_build_object(
                'linha', v_ordem,
                'numero', v_item ->> 'numero',
                'erro', sqlerrm
            );
        end;
    end loop;

    return jsonb_build_object('importados', v_total, 'erros', v_erros);
end;
$$;

create or replace function public.criar_ordem_coleta(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id     bigint;
    v_codigo text;
    v_token  uuid;
    v_pedidos_ids bigint[];
    v_snapshot jsonb;
begin
    perform public._exigir_operador();

    select coalesce(array_agg(value::bigint), '{}')
      into v_pedidos_ids
      from jsonb_array_elements_text(
               case when jsonb_typeof(p -> 'pedidosIds') = 'array'
                    then p -> 'pedidosIds' else '[]'::jsonb end
           ) as t(value);

    if cardinality(v_pedidos_ids) = 0 then
        raise exception 'Selecione pelo menos um cliente para a rota de coleta.'
            using errcode = '23502';
    end if;

    -- retrato dos clientes (o motorista lê daqui, sem acesso à tabela pedidos)
    select coalesce(jsonb_agg(jsonb_build_object(
               'cliente', pe.cliente,
               'endereco', coalesce(pe.endereco, pe.cidade || ' - ' || pe.uf)
           )), '[]'::jsonb)
      into v_snapshot
      from public.pedidos pe
     where pe.id = any (v_pedidos_ids);

    v_codigo := coalesce(nullif(btrim(p ->> 'codigo'), ''),
                         'COL-' || (1000 + floor(random() * 9000))::int);

    insert into public.ordens_coleta (
        id, codigo, frota, telefone, motorista_id,
        previsto_cavaletes, previsto_kits, previsto_cintas,
        status, clientes_snapshot
    ) values (
        coalesce(nullif(p ->> 'id', '')::bigint,
                 nextval(pg_get_serial_sequence('public.ordens_coleta', 'id'))),
        v_codigo,
        coalesce(nullif(btrim(p ->> 'frota'), ''), '---'),
        nullif(btrim(p ->> 'telefone'), ''),
        nullif(p ->> 'motoristaId', '')::uuid,
        coalesce((p ->> 'previstoCavaletes')::int, 0),
        coalesce((p ->> 'previstoKits')::int, 0),
        coalesce((p ->> 'previstoCintas')::int, 0),
        'Aguardando Frota',
        v_snapshot
    )
    returning id, token into v_id, v_token;

    insert into public.ordem_coleta_pedidos (ordem_id, pedido_id)
    select v_id, pid
      from unnest(v_pedidos_ids) as pid
    on conflict do nothing;

    return jsonb_build_object(
        'id', v_id,
        'codigo', v_codigo,
        'token', v_token,
        'url', '/#coleta=' || v_token
    );
end;
$$;

