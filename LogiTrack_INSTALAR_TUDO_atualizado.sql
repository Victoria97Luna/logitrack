    select * into v from public.ordens_coleta where id = p_id;
    if not found then
        raise exception 'Ordem % não encontrada.', p_id using errcode = 'P0002';
    end if;

    if v.status = 'Coletado no Local' then
        raise exception 'A ordem % já foi coletada e não pode ser editada.', v.codigo
            using errcode = '23514';
    end if;

    update public.ordens_coleta
