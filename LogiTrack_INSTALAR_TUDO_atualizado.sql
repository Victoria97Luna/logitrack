-- =====================================================================
-- LogiTrack — Cintas por quantidade (nova x usada)
-- =====================================================================
-- Regra:
--   * Lona e forro têm lacre: controle individual (já feito).
--   * Cinta NÃO tem lacre: o controle é por QUANTIDADE, separando
--     cintas NOVAS de cintas USADAS.
--   * Ao atribuir cintas a uma carga, é obrigatório dizer quantas são
--     novas e quantas são usadas.
--
-- O saldo e o extrato ficam no banco; o pedido guarda a separação.
--
-- Execute depois do 04_devolucao_lacres.sql. É idempotente.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. PEDIDO PASSA A GUARDAR NOVA x USADA
-- ---------------------------------------------------------------------
alter table public.pedidos
    add column if not exists cintas_novas  integer not null default 0,
    add column if not exists cintas_usadas integer not null default 0;

-- Pedidos que já existem: tudo o que estava lançado vira "nova"
-- (é o que estava saindo do galpão até hoje).
update public.pedidos
   set cintas_novas = cintas
 where cintas_novas = 0 and cintas_usadas = 0 and cintas > 0;

-- Garante a soma sempre coerente.
create or replace function public._somar_cintas()
returns trigger
language plpgsql
as $$
begin
    new.cintas_novas  := greatest(coalesce(new.cintas_novas, 0), 0);
    new.cintas_usadas := greatest(coalesce(new.cintas_usadas, 0), 0);
    new.cintas        := new.cintas_novas + new.cintas_usadas;
    return new;
end;
$$;

drop trigger if exists trg_somar_cintas on public.pedidos;
create trigger trg_somar_cintas
    before insert or update on public.pedidos
    for each row execute function public._somar_cintas();

-- ---------------------------------------------------------------------
-- 2. SALDO E EXTRATO DE CINTAS
-- ---------------------------------------------------------------------
create table if not exists public.cintas_saldo (
