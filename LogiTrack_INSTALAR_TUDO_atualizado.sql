create or replace function public.editar_pedido(p_id bigint, p jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_antes public.pedidos;
begin
    perform public._exigir_admin();

    select * into v_antes from public.pedidos where id = p_id;
    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    update public.pedidos
       set numero      = coalesce(nullif(btrim(p ->> 'numero'), ''), numero),
           cliente     = coalesce(nullif(btrim(p ->> 'cliente'), ''), cliente),
           cidade      = coalesce(nullif(btrim(p ->> 'cidade'), ''), cidade),
           uf          = upper(coalesce(nullif(btrim(p ->> 'uf'), ''), uf)),
           endereco    = coalesce(nullif(btrim(p ->> 'endereco'), ''), endereco),
           veiculo     = coalesce(nullif(p ->> 'veiculo', ''), veiculo),
           placa       = upper(coalesce(nullif(btrim(p ->> 'placa'), ''), placa)),
           motorista   = coalesce(nullif(btrim(p ->> 'motorista'), ''), motorista),
           data        = coalesce(public._para_data(p ->> 'data'), data),
           horario     = coalesce(public._para_hora(p ->> 'horario'), horario),
           cavaletes   = coalesce((p ->> 'cavaletes')::int, cavaletes),
           lonas       = coalesce((p ->> 'lonas')::int, lonas),
           forros      = coalesce((p ->> 'forros')::int, forros),
           cintas      = coalesce((p ->> 'cintas')::int, cintas),
           lacres_lona  = case when p ? 'lacresLona'  then public._para_text_array(p -> 'lacresLona')  else lacres_lona  end,
           lacres_forro = case when p ? 'lacresForro' then public._para_text_array(p -> 'lacresForro') else lacres_forro end,
           atualizado_em = now()
     where id = p_id;

    -- mantém o estoque coerente com os lacres editados
    if p ? 'lacresLona' or p ? 'lacresForro' then
        delete from public.estoque_lacres where pedido_id = p_id;

        insert into public.estoque_lacres (material, lacre, situacao, status, placa, data, pedido_id)
        select 'Lona 8x7', l, 'Uso', 'Em trânsito', v_antes.placa, v_antes.data, p_id
          from unnest(public._para_text_array(p -> 'lacresLona')) as l
        union all
        select 'Forro 5x3', f, 'Uso', 'Em trânsito', v_antes.placa, v_antes.data, p_id
          from unnest(public._para_text_array(p -> 'lacresForro')) as f;
    end if;

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (now(), 'Edição de Pedido', v_antes.numero,
            'Pedido alterado pela equipe', v_antes.placa,
            'Alteração registrada pelo administrador', auth.uid());
end;
$$;

