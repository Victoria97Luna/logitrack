comment on column public.pedidos.baixa_obs is
    'Por que a baixa foi dada. Ex.: Frota 114 autorizada pelo Gabriel, '
    'no galpão de Guaratinguetá, levando as travessas para a AGC.';
comment on column public.pedidos.baixa_autorizado is
    'Nome de quem autorizou a baixa.';

-- ---------------------------------------------------------------------
-- 2. Entregar / estornar entrega — exige justificativa
-- ---------------------------------------------------------------------
create or replace function public.alternar_entrega(
    p_id            bigint,
    p_observacao    text,
    p_autorizado    text
) returns jsonb
language plpgsql security definer
set search_path = public, pg_temp as $$
declare
    v public.pedidos;
    v_acao text;
begin
    perform public._exigir_baixa();

    if coalesce(btrim(p_observacao), '') = '' then
        raise exception 'Descreva o motivo da baixa antes de confirmar.'
            using errcode = '23502';
    end if;
    if coalesce(btrim(p_autorizado), '') = '' then
        raise exception 'Informe o nome de quem autorizou a baixa.'
            using errcode = '23502';
    end if;

    update public.pedidos
       set entregue = not entregue,
           data_entrega = case when not entregue then current_date else null end,
           baixa_obs = btrim(p_observacao),
           baixa_autorizado = btrim(p_autorizado),
           baixa_em = now(),
           baixa_por = auth.uid(),
           atualizado_em = now()
     where id = p_id
    returning * into v;

    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    v_acao := case when v.entregue then 'Baixa: pedido entregue'
                                   else 'Estorno: pedido reaberto' end;

    perform public._auditar(
        v_acao,
        'Pedido #' || v.numero,
        jsonb_build_object('cliente', v.cliente, 'placa', v.placa,
                           'entregue', v.entregue),
        p_observacao,
        p_autorizado
    );

    insert into public.historico (tipo, pedido, detalhes, obs, criado_por)
    values (v_acao, v.numero,
            'Cliente ' || coalesce(v.cliente, '---'),
            p_observacao || ' | Autorizado por: ' || p_autorizado,
            auth.uid());

    return jsonb_build_object(
        'id', v.id,
        'entregue', v.entregue,
        'dataEntrega', to_char(v.data_entrega, 'DD/MM/YYYY')
    );
end;
$$;

grant execute on function public.alternar_entrega(bigint, text, text) to authenticated;

-- ---------------------------------------------------------------------
-- 3. Baixa manual de coleta — exige justificativa
-- ---------------------------------------------------------------------
create or replace function public.baixa_manual_coleta(
    p_id          bigint,
    p_tipo        text,
    p_quem        text,
    p_observacao  text,
    p_autorizado  text
) returns void
language plpgsql security definer
set search_path = public, pg_temp as $$
declare
    v public.pedidos;
begin
    perform public._exigir_baixa();

    if p_tipo not in ('cavalete', 'lona') then
        raise exception 'Tipo de baixa inválido: %', p_tipo using errcode = '22023';
    end if;
    if coalesce(btrim(p_quem), '') = '' then
        raise exception 'Informe a frota ou o motorista que realizou a coleta.'
            using errcode = '23502';
    end if;
    if coalesce(btrim(p_observacao), '') = '' then
        raise exception 'Descreva o motivo da baixa antes de confirmar.'
            using errcode = '23502';
    end if;
    if coalesce(btrim(p_autorizado), '') = '' then
        raise exception 'Informe o nome de quem autorizou a baixa.'
            using errcode = '23502';
    end if;

    if p_tipo = 'cavalete' then
        update public.pedidos
           set coleta_cavalete_pendente = false,
               quem_coletou_cavalete = btrim(p_quem),
               baixa_obs = btrim(p_observacao),
               baixa_autorizado = btrim(p_autorizado),
               baixa_em = now(),
               baixa_por = auth.uid(),
               atualizado_em = now()
         where id = p_id returning * into v;
    else
        update public.pedidos
           set coleta_lona_pendente = false,
               quem_coletou_lona = btrim(p_quem),
               baixa_obs = btrim(p_observacao),
               baixa_autorizado = btrim(p_autorizado),
               baixa_em = now(),
               baixa_por = auth.uid(),
               atualizado_em = now()
         where id = p_id returning * into v;
    end if;

    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    perform public._auditar(
        case when p_tipo = 'cavalete'
             then 'Baixa: coleta de cavaletes'
             else 'Baixa: coleta de lonas' end,
        'Pedido #' || v.numero,
        jsonb_build_object('cliente', v.cliente, 'placa', v.placa, 'quem', p_quem),
        p_observacao,
        p_autorizado
    );

    insert into public.historico (tipo, pedido, detalhes, obs, criado_por)
    values (
        case when p_tipo = 'cavalete'
             then 'Baixa de Coleta: Cavaletes'
             else 'Baixa de Coleta: Lonas' end,
        v.numero,
        'Quem coletou: ' || p_quem,
        p_observacao || ' | Autorizado por: ' || p_autorizado,
        auth.uid()
    );
end;
$$;

grant execute on function public.baixa_manual_coleta(bigint, text, text, text, text) to authenticated;

