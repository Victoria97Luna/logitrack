    when (old.cintas_novas is distinct from new.cintas_novas
       or old.cintas_usadas is distinct from new.cintas_usadas)
    execute function public.ao_editar_pedido_cintas();

-- Ao excluir: as cintas voltam para o galpão na condição de origem.
create or replace function public.ao_excluir_pedido_cintas()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if old.cintas_novas > 0 then
        perform public._mov_cintas('Nova', old.cintas_novas, 'Devolução ao Estoque',
            old.numero, old.cliente,
            'Cintas novas devolvidas porque o pedido ' || old.numero || ' foi excluído');
    end if;
    if old.cintas_usadas > 0 then
        perform public._mov_cintas('Usada', old.cintas_usadas, 'Devolução ao Estoque',
            old.numero, old.cliente,
            'Cintas usadas devolvidas porque o pedido ' || old.numero || ' foi excluído');
    end if;
    return old;
end;
$$;

