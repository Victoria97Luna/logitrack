create or replace function public.listar_auditoria(
    p_limite  int default 200,
    p_usuario text default null,
    p_acao    text default null
)
returns jsonb
language plpgsql stable security definer
set search_path = public, pg_temp as $$
begin
    perform public._exigir_admin();

    return coalesce((
        select jsonb_agg(jsonb_build_object(
                   'id', a.id,
                   'quando', a.quando,
                   'usuario', a.usuario,
                   'papel', a.papel,
                   'acao', a.acao,
                   'alvo', a.alvo,
                   'detalhes', a.detalhes,
                   'justificativa', a.justificativa,
                   'autorizadoPor', a.autorizado_por
               ) order by a.quando desc)
          from (
                select *
                  from public.auditoria
                 where (p_usuario is null or public.auditoria.usuario ilike '%' || p_usuario || '%')
                   and (p_acao    is null or public.auditoria.acao = p_acao)
                 order by quando desc
                 limit greatest(1, least(coalesce(p_limite, 200), 1000))
               ) a
    ), '[]'::jsonb);
