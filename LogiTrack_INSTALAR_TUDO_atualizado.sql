-- ---------------------------------------------------------------------
-- 2. Criar um login novo
-- ---------------------------------------------------------------------
create or replace function public.criar_usuario(
    p_email  text,
    p_senha  text,
    p_nome   text,
    p_papel  text
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id     uuid := gen_random_uuid();
    v_email  text := lower(btrim(coalesce(p_email, '')));
    v_nome   text := btrim(coalesce(p_nome, ''));
    v_cols   text[];
    v_vals   text[];
    v_sql    text;
begin
    perform public._exigir_admin();

    if v_email = '' or position('@' in v_email) = 0 then
        raise exception 'Informe um e-mail válido.' using errcode = '22023';
    end if;
    if length(coalesce(p_senha, '')) < 6 then
        raise exception 'A senha precisa ter pelo menos 6 caracteres.' using errcode = '22023';
    end if;
    if p_papel not in ('admin', 'operador', 'consulta') then
        raise exception 'Patente inválida. Use admin, operador ou consulta.' using errcode = '22023';
    end if;
    if v_nome = '' then
        v_nome := split_part(v_email, '@', 1);
    end if;

    if exists (select 1 from auth.users where lower(email) = v_email) then
        raise exception 'Já existe um usuário com o e-mail %.', v_email using errcode = '23505';
    end if;

    -- -----------------------------------------------------------------
    -- Monta o INSERT apenas com as colunas que existem nesta instalação.
    -- O Supabase real tem instance_id, aud, role, identities etc. Um
    -- Postgres de teste pode ter só o essencial. Assim o script roda nos
    -- dois sem precisar de versão diferente.
    -- -----------------------------------------------------------------
    with desejado (col, expr) as (
        values
            ('id',                 quote_literal(v_id::text) || '::uuid'),
            ('instance_id',        quote_literal('00000000-0000-0000-0000-000000000000') || '::uuid'),
            ('aud',                quote_literal('authenticated')),
            ('role',               quote_literal('authenticated')),
            ('email',              quote_literal(v_email)),
            ('encrypted_password', 'extensions.crypt(' || quote_literal(p_senha) || ', extensions.gen_salt(''bf''))'),
            ('email_confirmed_at', 'now()'),
            ('created_at',         'now()'),
            ('updated_at',         'now()'),
            ('raw_app_meta_data',  quote_literal('{"provider":"email","providers":["email"]}') || '::jsonb'),
            ('raw_user_meta_data', 'jsonb_build_object(''nome'', ' || quote_literal(v_nome)
                                   || ', ''papel'', ' || quote_literal(p_papel) || ')')
    )
    select array_agg(d.col order by d.ord),
           array_agg(d.expr order by d.ord)
      into v_cols, v_vals
      from (
            select d.col, d.expr, row_number() over () as ord
              from desejado d
              join information_schema.columns c
                on c.table_schema = 'auth'
               and c.table_name   = 'users'
               and c.column_name  = d.col
           ) d;

    v_sql := 'insert into auth.users (' || array_to_string(v_cols, ', ') || ') values ('
             || array_to_string(v_vals, ', ') || ')';

    execute v_sql;

    -- identidade de e-mail (só existe no Supabase real; necessária para login)
    if exists (select 1 from information_schema.tables
                where table_schema = 'auth' and table_name = 'identities') then
        execute format(
            'insert into auth.identities (id, user_id, identity_data, provider, provider_id, last_sign_in_at, created_at, updated_at)
