-- ---------------------------------------------------------------------
-- 6. CONFIRMAÇÃO DA COLETA
--    (substitui finalizarColetaPeloMotorista do HTML)
-- ---------------------------------------------------------------------
-- Regras do original preservadas:
--   * grava coletadoCavaletes / coletadoKits / coletadoCintas
--   * frotaPreencheu = frota informada ou a frota da ordem
--   * status = 'Coletado no Local' e dataConclusao
--   * baixa automática nos pedidos vinculados
--   * registro no histórico
-- Tudo em uma transação: ou grava tudo, ou nada.

create or replace function public._aplicar_coleta(
    p_ordem        public.ordens_coleta,
    p_cavaletes    integer,
    p_kits         integer,
    p_cintas       integer,
    p_frota        text,
    p_obs          text,
    p_autor        uuid
) returns public.ordens_coleta
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem  public.ordens_coleta;
    v_frota  text;
    v_obs    text;
begin
    if p_cavaletes < 0 or p_kits < 0 or p_cintas < 0 then
        raise exception 'Quantidades coletadas não podem ser negativas.'
            using errcode = '22003';
    end if;

    v_frota := coalesce(nullif(btrim(coalesce(p_frota, '')), ''), p_ordem.frota);
    v_obs   := nullif(btrim(coalesce(p_obs, '')), '');

    update public.ordens_coleta
       set coletado_cavaletes = p_cavaletes,
           coletado_kits      = p_kits,
           coletado_cintas    = p_cintas,
           frota_preencheu    = v_frota,
           obs_frota          = v_obs,
           status             = 'Coletado no Local',
           data_conclusao     = now()
     where id = p_ordem.id
       and status = 'Aguardando Frota'
    returning * into v_ordem;

    if not found then
        raise exception 'A ordem % já foi confirmada.', p_ordem.codigo
            using errcode = '23505';
    end if;

    -- baixa automática nos pedidos vinculados
    update public.pedidos p
       set coleta_cavalete_pendente = false,
           coleta_lona_pendente     = false,
           quem_coletou_cavalete    = v_frota,
           quem_coletou_lona        = v_frota,
           atualizado_em            = now()
     where p.id in (
         select pedido_id
           from public.ordem_coleta_pedidos
          where ordem_id = p_ordem.id
     );

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (
        now(),
        'Coleta Realizada',
        v_ordem.codigo,
        format('%s recolheu %s Cav, %s Kits, %s Cintas',
               v_frota, p_cavaletes, p_kits, p_cintas),
        'Frota: ' || v_frota,
        'Coleta finalizada pelo motorista. Obs: ' || coalesce(v_obs, 'Sem divergências'),
        p_autor
    );

    return v_ordem;
end;
$$;

-- 6.1 Motorista logado confirma a própria coleta
create or replace function public.confirmar_coleta(
    p_ordem_id  bigint,
    p_cavaletes integer,
    p_kits      integer,
    p_cintas    integer,
    p_frota     text default null,
    p_obs       text default null
) returns public.ordens_coleta
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem public.ordens_coleta;
begin
    select * into v_ordem
      from public.ordens_coleta
     where id = p_ordem_id
       for update;

    if not found then
        raise exception 'Ordem de coleta não encontrada.' using errcode = 'P0002';
    end if;

    if not public.eh_admin() and v_ordem.motorista_id is distinct from auth.uid() then
        raise exception 'Esta coleta não está atribuída a você.' using errcode = '42501';
    end if;

    return public._aplicar_coleta(v_ordem, p_cavaletes, p_kits, p_cintas, p_frota, p_obs, auth.uid());
end;
$$;

grant execute on function public.confirmar_coleta(bigint, integer, integer, integer, text, text)
    to authenticated;

-- 6.2 Portal por link (celular do motorista, sem login)
--     Só funciona com token válido, não revogado e não expirado.
create or replace function public.portal_ordem(p_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select jsonb_build_object(
        'id', o.id,
        'codigo', o.codigo,
        'frota', o.frota,
        'previstoCavaletes', o.previsto_cavaletes,
        'previstoKits', o.previsto_kits,
        'previstoCintas', o.previsto_cintas,
        'coletadoCavaletes', o.coletado_cavaletes,
        'coletadoKits', o.coletado_kits,
        'coletadoCintas', o.coletado_cintas,
        'status', o.status,
        'obsFrota', o.obs_frota,
        'dataConclusao', o.data_conclusao,
        'clientesSnapshot', o.clientes_snapshot
    )
    from public.ordens_coleta o
    where o.token = p_token
      and o.token_revogado = false
      and o.token_expira_em > now();
$$;

create or replace function public.confirmar_coleta_portal(
    p_token     uuid,
    p_cavaletes integer,
    p_kits      integer,
    p_cintas    integer,
    p_frota     text default null,
    p_obs       text default null
) returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem public.ordens_coleta;
    v_final public.ordens_coleta;
begin
    select * into v_ordem
      from public.ordens_coleta
     where token = p_token
       and token_revogado = false
       and token_expira_em > now()
       for update;

    if not found then
        raise exception 'Link inválido, expirado ou revogado.' using errcode = '42501';
    end if;

    v_final := public._aplicar_coleta(v_ordem, p_cavaletes, p_kits, p_cintas, p_frota, p_obs, null);

    return jsonb_build_object(
        'ok', true,
        'codigo', v_final.codigo,
        'status', v_final.status
    );
end;
$$;

grant execute on function public.portal_ordem(uuid) to anon, authenticated;
grant execute on function public.confirmar_coleta_portal(uuid, integer, integer, integer, text, text)
    to anon, authenticated;

