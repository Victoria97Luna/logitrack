begin
    if not public.eh_admin() then
        raise exception 'Acesso restrito à equipe administrativa.' using errcode = '42501';
    end if;
    if p_cidade not in ('Campo Belo', 'Guaratinguetá') then
        raise exception 'Selecione Campo Belo ou Guaratinguetá.' using errcode = '22023';
    end if;
    select jsonb_build_object(
        'cidade', p_cidade,
        'lacresLona', coalesce((select jsonb_agg(m.lacre order by m.lacre)
            from public.estoque_materiais_local m where m.cidade=p_cidade
            and m.material='LONA' and m.situacao='Disponível'), '[]'::jsonb),
        'lacresForro', coalesce((select jsonb_agg(m.lacre order by m.lacre)
            from public.estoque_materiais_local m where m.cidade=p_cidade
            and m.material='FORRO' and m.situacao='Disponível'), '[]'::jsonb),
        'cintasNovasDisponiveis', coalesce(c.cintas_novas, 0),
        'cintasUsadasDisponiveis', coalesce(c.cintas_usadas, 0)
    ) into v_resultado
      from (select 1) q left join public.estoque_cintas_local c on c.cidade=p_cidade;
    return v_resultado;
end;
$$;
