-- ---------------------------------------------------------------------
-- Recebe a lista já convertida em JSON pelo navegador (o XLSX continua
-- sendo lido no cliente). Grava tudo numa transação: se uma linha
-- falhar, nada entra. Devolve quantos entraram.

create or replace function public.importar_pedidos(p_lista jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_item    jsonb;
    v_total   int := 0;
    v_erros   jsonb := '[]'::jsonb;
    v_ordem   int := 0;
begin
    perform public._exigir_admin();

    if jsonb_typeof(p_lista) <> 'array' then
        raise exception 'A importação espera uma lista de pedidos.' using errcode = '22023';
    end if;

    for v_item in select * from jsonb_array_elements(p_lista)
    loop
        v_ordem := v_ordem + 1;
        begin
            perform public.criar_pedido(v_item);
            v_total := v_total + 1;
        exception when others then
            v_erros := v_erros || jsonb_build_object(
                'linha', v_ordem,
                'numero', v_item ->> 'numero',
                'erro', sqlerrm
            );
        end;
    end loop;

    return jsonb_build_object('importados', v_total, 'erros', v_erros);
end;
$$;

