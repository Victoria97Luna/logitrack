-- true se o usuário logado é administrador.
-- SECURITY DEFINER: lê profiles sem passar pela RLS (evita recursão).
create or replace function public.eh_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    select exists (
        select 1
          from public.profiles
         where id = auth.uid()
           and papel = 'admin'
           and ativo
    );
$$;

