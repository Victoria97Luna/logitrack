-- =====================================================================
-- LogiTrack — Script 11: rota de coleta por cliente
--
-- Rode DEPOIS do script 10.
--
-- O que muda
-- ----------
-- Antes a ordem de coleta guardava só três totais (cavaletes, kits,
-- cintas) para a rota inteira. O motorista informava um número único e
-- o sistema dava baixa em tudo.
--
-- Agora cada parada da rota é uma linha, com o previsto e o coletado
-- DAQUELE cliente:
--
--   Parada 1 — Unibox Comércios de Vidros
--              previsto: 3 cavaletes, 6 lonas, 6 forros, 12 cintas
--              coletado: 3 cavaletes, 4 lonas, 6 forros, 12 cintas
--
-- O portal mostra cada parada com o endereço completo e um link do
-- Google Maps, permite alterar as quantidades para mais ou para menos,
-- e exige observação quando alguma quantidade sai diferente do previsto.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. A tabela de paradas da rota
-- ---------------------------------------------------------------------
create table if not exists public.ordem_coleta_itens (
    id              bigint primary key generated by default as identity,
    ordem_id        bigint not null references public.ordens_coleta (id) on delete cascade,
    pedido_id       bigint references public.pedidos (id) on delete set null,
    parada          integer not null default 1,

    -- retrato do cliente no momento em que a rota foi montada
    cliente         text not null,
    endereco        text,
    cidade          text,
    uf              text,
    telefone        text,

    -- o que o escritório espera recolher neste local
    prev_cavaletes  integer not null default 0 check (prev_cavaletes >= 0),
    prev_lonas      integer not null default 0 check (prev_lonas   >= 0),
    prev_forros     integer not null default 0 check (prev_forros  >= 0),
    prev_cintas     integer not null default 0 check (prev_cintas  >= 0),

    -- o que o motorista realmente recolheu
    colet_cavaletes integer check (colet_cavaletes >= 0),
    colet_lonas     integer check (colet_lonas     >= 0),
    colet_forros    integer check (colet_forros    >= 0),
    colet_cintas    integer check (colet_cintas    >= 0),

    obs_item        text,
    conferido_em    timestamptz
);

create index if not exists idx_oc_itens_ordem on public.ordem_coleta_itens (ordem_id, parada);

comment on table public.ordem_coleta_itens is
    'Cada parada da rota de coleta: cliente, endereço e as quantidades '
    'previstas e efetivamente coletadas naquele local.';

-- ---------------------------------------------------------------------
-- 2. Endereço completo e link do Google Maps
-- ---------------------------------------------------------------------

-- Junta logradouro + cidade + UF sem repetir pedaço nem deixar vírgula solta.
create or replace function public._endereco_completo(
    p_endereco text, p_cidade text, p_uf text
) returns text
language sql immutable as $$
    select nullif(btrim(
        concat_ws(', ',
            nullif(btrim(coalesce(p_endereco, '')), ''),
            nullif(btrim(coalesce(p_cidade, '')), ''),
            nullif(btrim(coalesce(p_uf, '')), '')
        )
    ), '');
$$;

-- Link que abre o Google Maps já apontando para o endereço.
-- Serve tanto no celular quanto no computador.
create or replace function public._link_maps(
    p_endereco text, p_cidade text, p_uf text
) returns text
language sql immutable as $$
    select 'https://www.google.com/maps/dir/?api=1&destination=' ||
           replace(replace(replace(
               public._endereco_completo(p_endereco, p_cidade, p_uf),
               ' ', '%20'), '#', '%23'), '&', '%26');
$$;

-- Monta a rota completa com todas as paradas, na ordem, num único link.
-- Usado pelo botão "Abrir rota no Maps" do portal do motorista.
create or replace function public._link_rota_maps(p_ordem_id bigint)
returns text
language sql stable security definer
set search_path = public, pg_temp as $$
    with pontos as (
        select public._endereco_completo(endereco, cidade, uf) as ponto,
               parada
          from public.ordem_coleta_itens
         where ordem_id = p_ordem_id
         order by parada
    ), validos as (
        select ponto from pontos where ponto is not null
    )
    select case
        when (select count(*) from validos) = 0 then null
        when (select count(*) from validos) = 1 then
            'https://www.google.com/maps/dir/?api=1&destination=' ||
            (select replace(ponto, ' ', '%20') from validos)
        else
            -- primeira parada é o destino; as demais viram waypoints
            'https://www.google.com/maps/dir/?api=1&destination=' ||
            (select replace(ponto, ' ', '%20') from validos offset 0 limit 1) ||
            '&waypoints=' ||
            (select string_agg(replace(ponto, ' ', '%20'), '|')
               from (select ponto from validos offset 1) w)
    end;
$$;

-- ---------------------------------------------------------------------
-- 3. Criar a ordem já com as paradas
-- ---------------------------------------------------------------------
create or replace function public.criar_ordem_coleta(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id          bigint;
    v_codigo      text;
    v_token       uuid;
    v_pedidos_ids bigint[];
    v_parada      int := 0;
    v_ped         record;
    v_cav         int;
    v_lon         int;
    v_for         int;
    v_cin         int;
    v_tot_cav     int := 0;
    v_tot_lon     int := 0;
    v_tot_for     int := 0;
    v_tot_cin     int := 0;
begin
    perform public._exigir_coleta();

    select coalesce(array_agg(distinct value::bigint), '{}')
      into v_pedidos_ids
      from jsonb_array_elements_text(
               case when jsonb_typeof(p -> 'pedidosIds') = 'array'
                    then p -> 'pedidosIds' else '[]'::jsonb end
           ) as t(value);

    if cardinality(v_pedidos_ids) = 0 then
        raise exception 'Selecione pelo menos um cliente para a rota de coleta.'
            using errcode = '23502';
    end if;

    v_codigo := coalesce(nullif(btrim(p ->> 'codigo'), ''),
                         'COL-' || (1000 + floor(random() * 9000))::int);

    insert into public.ordens_coleta (
        codigo, frota, telefone, motorista_id,
        previsto_cavaletes, previsto_kits, previsto_cintas,
        status, clientes_snapshot
    ) values (
        v_codigo,
        coalesce(nullif(btrim(p ->> 'frota'), ''), '---'),
        nullif(btrim(p ->> 'telefone'), ''),
        nullif(p ->> 'motoristaId', '')::uuid,
        0, 0, 0,
        'Aguardando Frota',
        '[]'::jsonb
    )
    returning id, token into v_id, v_token;

    -- Uma parada por pedido, RESPEITANDO a ordem em que foram escolhidos
    -- na tela (a rota segue a sequência que o escritório montou).
    for v_ped in
        select pe.*
          from public.pedidos pe
          join unnest(v_pedidos_ids) with ordinality as t(id, pos)
            on t.id = pe.id
         order by t.pos
    loop
        v_parada := v_parada + 1;

        -- Só entra o que está de fato pendente de coleta naquele cliente.
        v_cav := case when v_ped.coleta_cavalete_pendente then v_ped.cavaletes else 0 end;
        v_lon := case when v_ped.coleta_lona_pendente     then v_ped.lonas     else 0 end;
        v_for := case when v_ped.coleta_lona_pendente     then v_ped.forros    else 0 end;
        v_cin := case when v_ped.coleta_lona_pendente     then v_ped.cintas    else 0 end;

        insert into public.ordem_coleta_itens (
            ordem_id, pedido_id, parada,
            cliente, endereco, cidade, uf,
            prev_cavaletes, prev_lonas, prev_forros, prev_cintas
        ) values (
            v_id, v_ped.id, v_parada,
            v_ped.cliente, v_ped.endereco, v_ped.cidade, v_ped.uf,
            v_cav, v_lon, v_for, v_cin
        );

        v_tot_cav := v_tot_cav + v_cav;
        v_tot_lon := v_tot_lon + v_lon;
        v_tot_for := v_tot_for + v_for;
        v_tot_cin := v_tot_cin + v_cin;

        insert into public.ordem_coleta_pedidos (ordem_id, pedido_id)
        values (v_id, v_ped.id)
        on conflict do nothing;
    end loop;

    -- Totais da rota (o "kits" do sistema antigo = lonas + forros).
    -- Guardamos lonas e forros juntos em previsto_kits por compatibilidade,
    -- e o detalhe fino fica nas paradas.
    update public.ordens_coleta
       set previsto_cavaletes = v_tot_cav,
           previsto_kits      = greatest(v_tot_lon, v_tot_for),
           previsto_cintas    = v_tot_cin,
           clientes_snapshot  = (
               select coalesce(jsonb_agg(jsonb_build_object(
                          'parada', i.parada,
                          'cliente', i.cliente,
                          'endereco', public._endereco_completo(i.endereco, i.cidade, i.uf),
                          'maps', public._link_maps(i.endereco, i.cidade, i.uf)
                      ) order by i.parada), '[]'::jsonb)
                 from public.ordem_coleta_itens i
                where i.ordem_id = v_id
           )
     where id = v_id;

    perform public._auditar(
        'Criou ordem de coleta',
        'Ordem ' || v_codigo,
        jsonb_build_object('frota', coalesce(p ->> 'frota', ''),
                           'paradas', v_parada,
                           'pedidos', v_pedidos_ids)
    );

    return jsonb_build_object(
        'id', v_id,
        'codigo', v_codigo,
        'token', v_token,
        'paradas', v_parada,
        'previstoCavaletes', v_tot_cav,
        'previstoLonas', v_tot_lon,
        'previstoForros', v_tot_for,
        'previstoCintas', v_tot_cin
    );
end;
$$;

grant execute on function public.criar_ordem_coleta(jsonb) to authenticated;

