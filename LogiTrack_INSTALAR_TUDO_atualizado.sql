-- Cria o pedido e baixa os materiais na mesma transação.
create or replace function public.criar_pedido_com_estoque(
    p jsonb, p_kit_proprio boolean default false, p_estoque_cidade text default null
) returns bigint language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
    v_id bigint;
    v_pedido public.pedidos;
    v_payload jsonb;
    v_cintas public.estoque_cintas_local;
    v_lonas text[];
    v_forros text[];
    v_lacre text;
    v_qtd integer;
begin
    perform public._exigir_lancar_pedido();
    if coalesce(p_kit_proprio, false) then
        v_payload := p - 'lacresLona' - 'lacresForro';
        v_id := public.criar_pedido(v_payload);
        update public.pedidos set kit_proprio=true, estoque_cidade=null where id=v_id;
        return v_id;
    end if;
    if p_estoque_cidade not in ('Campo Belo', 'Guaratinguetá') then
        raise exception 'Selecione o estoque Campo Belo ou Guaratinguetá.' using errcode = '22023';
    end if;

    v_lonas := public._para_text_array(p -> 'lacresLona');
    v_forros := public._para_text_array(p -> 'lacresForro');
    v_id := public.criar_pedido(p);
    select * into v_pedido from public.pedidos where id=v_id for update;

    if cardinality(v_lonas) <> v_pedido.lonas then
        raise exception 'Selecione um lacre de lona para cada lona do pedido.' using errcode = '22023';
    end if;
    if cardinality(v_forros) <> v_pedido.forros then
        raise exception 'Selecione um lacre de forro para cada forro do pedido.' using errcode = '22023';
    end if;
    for v_lacre in select unnest(v_lonas) loop
        update public.estoque_materiais_local set situacao='Em trânsito', pedido_id=v_id
         where cidade=p_estoque_cidade and material='LONA' and lacre=v_lacre
           and situacao='Disponível';
        get diagnostics v_qtd = row_count;
        if v_qtd <> 1 then
            raise exception 'O lacre de lona % não está disponível no estoque de %.',
                v_lacre, p_estoque_cidade using errcode = '23514';
        end if;
    end loop;
    for v_lacre in select unnest(v_forros) loop
        update public.estoque_materiais_local set situacao='Em trânsito', pedido_id=v_id
         where cidade=p_estoque_cidade and material='FORRO' and lacre=v_lacre
           and situacao='Disponível';
        get diagnostics v_qtd = row_count;
        if v_qtd <> 1 then
            raise exception 'O lacre de forro % não está disponível no estoque de %.',
                v_lacre, p_estoque_cidade using errcode = '23514';
        end if;
    end loop;

    select * into v_cintas from public.estoque_cintas_local
     where cidade=p_estoque_cidade for update;
    if not found then
        raise exception 'O estoque de cintas de % ainda não foi configurado.',
            p_estoque_cidade using errcode = 'P0002';
    end if;
    if v_cintas.cintas_novas < coalesce(v_pedido.cintas_novas,0)
       or v_cintas.cintas_usadas < coalesce(v_pedido.cintas_usadas,0) then
        raise exception 'Quantidade de cintas insuficiente no estoque de %.',
            p_estoque_cidade using errcode = '23514';
    end if;
    update public.estoque_cintas_local set
        cintas_novas=cintas_novas-coalesce(v_pedido.cintas_novas,0),
        cintas_usadas=cintas_usadas-coalesce(v_pedido.cintas_usadas,0),
        atualizado_em=now()
     where cidade=p_estoque_cidade;
    update public.pedidos set kit_proprio=false, estoque_cidade=p_estoque_cidade where id=v_id;
    return v_id;
end;
$$;
grant execute on function public.criar_pedido_com_estoque(jsonb, boolean, text)
    to authenticated;

create or replace function public.detalhes_kit_pedidos()
returns jsonb language sql stable security definer
set search_path = public, pg_temp
as $$
    select case when public.eh_admin() then coalesce(jsonb_agg(jsonb_build_object(
        'id', p.id, 'kitProprio', p.kit_proprio, 'estoqueCidade', p.estoque_cidade
    ) order by p.id desc), '[]'::jsonb) else '[]'::jsonb end
    from public.pedidos p;
$$;
grant execute on function public.detalhes_kit_pedidos() to authenticated;

commit;

