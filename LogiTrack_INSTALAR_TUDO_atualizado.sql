           ), '[]'::jsonb)
         where o.id = p_id;
    end if;

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (now(), 'Edição de Ordem', v.codigo,
            'Ordem de coleta alterada', v.frota,
