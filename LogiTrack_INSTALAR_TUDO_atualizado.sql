-- =====================================================================
-- LogiTrack — Script 14: rota sugerida por endereço
--
-- Rode DEPOIS do script 13.
--
-- O que muda
-- ----------
-- Até aqui a rota saía na ordem em que o escritório marcava os clientes
-- na tela. Isso não tem nada a ver com logística: quem marcou primeiro
-- virava a primeira parada.
--
-- Agora a sugestão vem do ENDEREÇO:
--   • clientes da mesma cidade ficam juntos (não pula de cidade e volta);
--   • dentro da cidade, a sequência segue a rua;
--   • cidades com mais paradas vêm primeiro (é onde o motorista perde
--     mais tempo), e as demais em ordem alfabética.
--
-- Isso é uma SUGESTÃO, não uma obrigação: o motorista pode reordenar as
-- paradas no portal como achar melhor para o dia dele (trânsito, obra,
-- horário do cliente).
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Chave de ordenação sem depender de extensão de acento
-- ---------------------------------------------------------------------
create or replace function public._chave_ordem(p_texto text)
returns text
language sql immutable as $$
    select btrim(
        translate(
            lower(coalesce(p_texto, '')),
            'áàâãäéèêëíìîïóòôõöúùûüçñ',
            'aaaaaeeeeiiiiooooouuuucn'
        )
    );
$$;

-- ---------------------------------------------------------------------
-- 2. A sugestão de sequência
-- ---------------------------------------------------------------------
create or replace function public._ordem_sugerida(p_ids bigint[])
returns table (pedido_id bigint, posicao int)
language sql stable
as $$
    with base as (
        select p.id,
               p.cliente,
               p.cidade,
               p.uf,
               coalesce(p.endereco, '') as endereco
          from public.pedidos p
         where p.id = any (p_ids)
    ),
    por_cidade as (
        select b.*,
               count(*) over (partition by public._chave_ordem(b.cidade), b.uf) as qtd_cidade
          from base b
    )
    select o.id,
           row_number() over (
               order by
                   -- 1) cidade com mais paradas primeiro
                   o.qtd_cidade desc,
                   -- 2) depois as cidades em ordem alfabética
                   public._chave_ordem(o.cidade),
                   o.uf,
                   -- 3) dentro da cidade, pela rua
                   public._chave_ordem(o.endereco),
                   -- 4) desempate pelo nome do cliente
                   public._chave_ordem(o.cliente)
           )::int
      from por_cidade o;
$$;

grant execute on function public._ordem_sugerida(bigint[]) to authenticated;

-- ---------------------------------------------------------------------
-- 3. Criar a ordem já na sequência sugerida
-- ---------------------------------------------------------------------
create or replace function public.criar_ordem_coleta(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id          bigint;
    v_codigo      text;
    v_token       uuid;
    v_pedidos_ids bigint[];
    v_parada      int := 0;
    v_ped         record;
    v_cav         int;
    v_lon         int;
    v_for         int;
    v_cin         int;
    v_tot_cav     int := 0;
    v_tot_lon     int := 0;
    v_tot_for     int := 0;
    v_tot_cin     int := 0;
begin
    perform public._exigir_coleta();

    select coalesce(array_agg(distinct value::bigint), '{}')
      into v_pedidos_ids
      from jsonb_array_elements_text(
               case when jsonb_typeof(p -> 'pedidosIds') = 'array'
                    then p -> 'pedidosIds' else '[]'::jsonb end
           ) as t(value);

    if cardinality(v_pedidos_ids) = 0 then
        raise exception 'Selecione pelo menos um cliente para a rota de coleta.'
            using errcode = '23502';
    end if;

    v_codigo := coalesce(nullif(btrim(p ->> 'codigo'), ''),
                         'COL-' || (1000 + floor(random() * 9000))::int);

    insert into public.ordens_coleta (
        codigo, frota, telefone, motorista_id,
        previsto_cavaletes, previsto_kits, previsto_cintas,
        status, clientes_snapshot
    ) values (
        v_codigo,
        coalesce(nullif(btrim(p ->> 'frota'), ''), '---'),
        nullif(btrim(p ->> 'telefone'), ''),
        nullif(p ->> 'motoristaId', '')::uuid,
        0, 0, 0,
        'Aguardando Frota',
        '[]'::jsonb
    )
    returning id, token into v_id, v_token;

    -- As paradas entram na SEQUÊNCIA SUGERIDA PELO ENDEREÇO,
    -- não na ordem em que foram marcadas na tela.
    for v_ped in
        select pe.*
          from public.pedidos pe
          join public._ordem_sugerida(v_pedidos_ids) s on s.pedido_id = pe.id
         order by s.posicao
    loop
        v_parada := v_parada + 1;

        v_cav := case when v_ped.coleta_cavalete_pendente then v_ped.cavaletes else 0 end;
        v_lon := case when v_ped.coleta_lona_pendente     then v_ped.lonas     else 0 end;
        v_for := case when v_ped.coleta_lona_pendente     then v_ped.forros    else 0 end;
        v_cin := case when v_ped.coleta_lona_pendente     then v_ped.cintas    else 0 end;

        insert into public.ordem_coleta_itens (
            ordem_id, pedido_id, parada,
            cliente, endereco, cidade, uf,
            prev_cavaletes, prev_lonas, prev_forros, prev_cintas
        ) values (
            v_id, v_ped.id, v_parada,
            v_ped.cliente, v_ped.endereco, v_ped.cidade, v_ped.uf,
            v_cav, v_lon, v_for, v_cin
        );

        v_tot_cav := v_tot_cav + v_cav;
        v_tot_lon := v_tot_lon + v_lon;
        v_tot_for := v_tot_for + v_for;
        v_tot_cin := v_tot_cin + v_cin;

        insert into public.ordem_coleta_pedidos (ordem_id, pedido_id)
        values (v_id, v_ped.id)
        on conflict do nothing;
    end loop;

    update public.ordens_coleta
       set previsto_cavaletes = v_tot_cav,
           previsto_kits      = greatest(v_tot_lon, v_tot_for),
           previsto_cintas    = v_tot_cin,
           clientes_snapshot  = (
               select coalesce(jsonb_agg(jsonb_build_object(
                          'parada', i.parada,
                          'cliente', i.cliente,
                          'endereco', public._endereco_completo(i.endereco, i.cidade, i.uf),
                          'maps', public._link_maps(i.endereco, i.cidade, i.uf)
                      ) order by i.parada), '[]'::jsonb)
                 from public.ordem_coleta_itens i
                where i.ordem_id = v_id
           )
     where id = v_id;

    perform public._auditar(
        'Criou ordem de coleta',
        'Ordem ' || v_codigo,
        jsonb_build_object('frota', coalesce(p ->> 'frota', ''),
                           'paradas', v_parada,
                           'pedidos', v_pedidos_ids,
                           'ordem', 'sugerida por endereco')
    );

    return jsonb_build_object(
        'id', v_id,
        'codigo', v_codigo,
        'token', v_token,
        'paradas', v_parada,
        'previstoCavaletes', v_tot_cav,
        'previstoLonas', v_tot_lon,
        'previstoForros', v_tot_for,
        'previstoCintas', v_tot_cin
    );
end;
$$;

grant execute on function public.criar_ordem_coleta(jsonb) to authenticated;

-- ---------------------------------------------------------------------
-- 4. O motorista reordena como quiser
-- ---------------------------------------------------------------------
create or replace function public.reordenar_paradas_portal(
    p_token   uuid,
    p_item_ids jsonb          -- lista de itemId na nova ordem
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem public.ordens_coleta;
    v_novos bigint[];
    v_pos   int := 0;
    v_id    bigint;
begin
    select * into v_ordem
      from public.ordens_coleta
     where token = p_token
       and token_revogado = false
       and token_expira_em > now()
       for update;

    if not found then
        raise exception 'Link inválido, expirado ou revogado.' using errcode = '42501';
    end if;

    if v_ordem.status = 'Coletado no Local' then
        raise exception 'Esta coleta já foi confirmada.' using errcode = '23505';
    end if;

    select coalesce(array_agg((value #>> '{}')::bigint), '{}')
      into v_novos
      from jsonb_array_elements(
               case when jsonb_typeof(p_item_ids) = 'array'
                    then p_item_ids else '[]'::jsonb end
           );

    -- a lista precisa conter exatamente as paradas desta rota
    if (select count(*) from public.ordem_coleta_itens
         where ordem_id = v_ordem.id and id = any (v_novos)) <> cardinality(v_novos) then
        raise exception 'A lista de paradas não confere com esta rota.' using errcode = '22023';
    end if;

    foreach v_id in array v_novos loop
        v_pos := v_pos + 1;
        update public.ordem_coleta_itens
           set parada = v_pos
         where id = v_id and ordem_id = v_ordem.id;
    end loop;

    perform public._auditar(
        'Reordenou a rota',
        'Ordem ' || v_ordem.codigo,
        jsonb_build_object('ordem', v_novos)
    );

    return jsonb_build_object('ok', true, 'paradas', cardinality(v_novos));
end;
$$;

