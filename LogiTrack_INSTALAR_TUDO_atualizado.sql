-- 7.1 Novo pedido -> baixa dos lacres no estoque + histórico "Saída Carga"
create or replace function public.ao_criar_pedido()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    -- lacres de lona
    insert into public.estoque_lacres (material, lacre, situacao, status, placa, data, pedido_id)
    select 'Lona 8x7', l, 'Uso', 'Em trânsito', new.placa, new.data, new.id
      from unnest(new.lacres_lona) as l
     where l <> '';

    -- lacres de forro
    insert into public.estoque_lacres (material, lacre, situacao, status, placa, data, pedido_id)
    select 'Forro 5x3', f, 'Uso', 'Em trânsito', new.placa, new.data, new.id
      from unnest(new.lacres_forro) as f
     where f <> '';

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (
        (new.data + new.horario)::timestamptz,
        'Saída Carga',
        new.numero,
        new.veiculo || ' - ' || new.motorista,
        new.placa || ' • Lacres: ' ||
            array_to_string(new.lacres_lona || new.lacres_forro, ', '),
        'Carga faturada para ' || new.cliente || ' (' || new.cidade || '/' || new.uf || ')',
        auth.uid()
    );

    return new;
end;
$$;

drop trigger if exists trg_ao_criar_pedido on public.pedidos;
create trigger trg_ao_criar_pedido
