-- ---------------------------------------------------------------------
-- 9. COLETA DEVOLVE AS CINTAS COMO USADAS
-- ---------------------------------------------------------------------
-- Quando o motorista recolhe as cintas, elas voltam para o galpão já
-- usadas — é isso que abastece o saldo de "usada".
-- Substitui _aplicar_coleta do 01 somando esta regra.

create or replace function public._aplicar_coleta(
    p_ordem        public.ordens_coleta,
    p_cavaletes    integer,
    p_kits         integer,
    p_cintas       integer,
    p_frota        text,
    p_obs          text,
    p_autor        uuid
) returns public.ordens_coleta
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem  public.ordens_coleta;
    v_frota  text;
    v_obs    text;
begin
    if p_cavaletes < 0 or p_kits < 0 or p_cintas < 0 then
        raise exception 'Quantidades coletadas não podem ser negativas.'
            using errcode = '22003';
    end if;

    v_frota := coalesce(nullif(btrim(coalesce(p_frota, '')), ''), p_ordem.frota);
    v_obs   := nullif(btrim(coalesce(p_obs, '')), '');

    update public.ordens_coleta
       set coletado_cavaletes = p_cavaletes,
           coletado_kits      = p_kits,
           coletado_cintas    = p_cintas,
           frota_preencheu    = v_frota,
           obs_frota          = v_obs,
           status             = 'Coletado no Local',
           data_conclusao     = now()
     where id = p_ordem.id
       and status = 'Aguardando Frota'
    returning * into v_ordem;

    if not found then
        raise exception 'A ordem % já foi confirmada.', p_ordem.codigo
            using errcode = '23505';
    end if;

    update public.pedidos p
       set coleta_cavalete_pendente = false,
           coleta_lona_pendente     = false,
           quem_coletou_cavalete    = v_frota,
           quem_coletou_lona        = v_frota,
           atualizado_em            = now()
     where p.id in (
         select pedido_id from public.ordem_coleta_pedidos where ordem_id = p_ordem.id
     );

    -- cintas recolhidas entram no saldo como USADAS
    if p_cintas > 0 then
        perform public._mov_cintas('Usada', p_cintas, 'Coleta Realizada',
            v_ordem.codigo, null,
            'Cintas recolhidas pela frota ' || v_frota || ' e devolvidas ao galpão como usadas');
    end if;

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (
        now(), 'Coleta Realizada', v_ordem.codigo,
        format('%s recolheu %s Cav, %s Kits, %s Cintas',
               v_frota, p_cavaletes, p_kits, p_cintas),
        'Frota: ' || v_frota,
        'Coleta finalizada pelo motorista. Obs: ' || coalesce(v_obs, 'Sem divergências'),
        p_autor
    );

    return v_ordem;
end;
$$;

