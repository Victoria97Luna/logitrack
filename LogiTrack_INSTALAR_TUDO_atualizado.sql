-- =====================================================================
-- LogiTrack — Script 16: regra dos cavaletes
--
-- Rode DEPOIS do script 15.
--
-- REGRA
--   1 cavalete SEMPRE leva 1 lona + 1 forro + 4 cintas.
--
--   Por isso, ao criar ou editar um pedido, o banco recalcula:
--     lonas  = cavaletes
--     forros = cavaletes
--     cintas = cavaletes x 4
--
--   Mais de 2 cavaletes é EXCEÇÃO (bitrem / carreta maior). É permitido,
--   mas fica marcado no histórico, porque é situação rara e precisa ser
--   confirmada por quem cadastrou.
--
--   Se o operador mandar uma quantidade de lona menor que a de cavalete,
--   a função corrige para cima — cavalete solto não existe na operação.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Função única da proporção (usada no criar e no editar)
-- ---------------------------------------------------------------------
create or replace function public._normalizar_cavaletes(
    p_cavaletes integer,
    p_lonas     integer default null,
    p_forros    integer default null,
    p_cintas    integer default null
)
returns jsonb
language plpgsql immutable
as $$
declare
    v_cav int;
    v_lon int;
    v_for int;
    v_cin int;
begin
    v_cav := coalesce(p_cavaletes, 1);
    if v_cav < 1 then
        v_cav := 1;
    end if;

    -- o cavalete manda: nunca menos que 1 lona/forro por cavalete
    v_lon := greatest(coalesce(p_lonas, v_cav), v_cav);
    v_for := greatest(coalesce(p_forros, v_cav), v_cav);

    -- cintas: no mínimo 4 por cavalete
    v_cin := greatest(coalesce(p_cintas, v_cav * 4), v_cav * 4);

    return jsonb_build_object(
        'cavaletes', v_cav,
        'lonas', v_lon,
        'forros', v_for,
        'cintas', v_cin,
        'excepcional', v_cav > 2
    );
end;
$$;

grant execute on function public._normalizar_cavaletes(integer, integer, integer, integer)
    to authenticated, anon;

-- ---------------------------------------------------------------------
-- 2. criar_pedido aplica a regra antes de gravar
-- ---------------------------------------------------------------------
create or replace function public.criar_pedido(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id     bigint;
    v_novas  int;
    v_usadas int;
    v_total  int;
    v_end    text;
    v_regra  jsonb;
    v_cav    int;
    v_lon    int;
    v_for    int;
    v_cin    int;
begin
    perform public._exigir_lancar_pedido();

    if coalesce(btrim(p ->> 'numero'), '') = '' then
        raise exception 'O número do pedido é obrigatório.' using errcode = '23502';
    end if;
    if coalesce(btrim(p ->> 'cliente'), '') = '' then
        raise exception 'O cliente é obrigatório.' using errcode = '23502';
    end if;

    -- ENDEREÇO: obrigatório, com número, para o mapa funcionar
    v_end := btrim(coalesce(p ->> 'endereco', ''));

    if v_end = '' then
        raise exception 'O endereço completo é obrigatório. Sem ele o motorista não chega e o mapa não é gerado.'
            using errcode = '23502';
    end if;
    if length(v_end) < 10 then
        raise exception 'Endereço incompleto: informe rua, número e bairro.'
            using errcode = '22023';
    end if;
    if v_end !~ '[0-9]' then
        raise exception 'Falta o número do imóvel no endereço (ex.: Av. Rio Verde, 1200 - Vila Rosa).'
            using errcode = '22023';
    end if;
    if coalesce(btrim(p ->> 'cidade'), '') = '' then
        raise exception 'A cidade é obrigatória — é por ela que a rota é montada.'
            using errcode = '23502';
    end if;
    if coalesce(btrim(p ->> 'uf'), '') = '' then
        raise exception 'O estado (UF) é obrigatório.' using errcode = '23502';
    end if;

    -- REGRA DOS CAVALETES: 1 cavalete = 1 lona + 1 forro + 4 cintas
    v_regra := public._normalizar_cavaletes(
        coalesce((p ->> 'cavaletes')::int, 1),
        (p ->> 'lonas')::int,
        (p ->> 'forros')::int,
        null
    );

    v_cav := (v_regra ->> 'cavaletes')::int;
    v_lon := (v_regra ->> 'lonas')::int;
    v_for := (v_regra ->> 'forros')::int;
    v_cin := (v_regra ->> 'cintas')::int;

    -- divisão nova/velha das cintas
    v_total  := v_cin;
    v_novas  := coalesce((p ->> 'cintasNovas')::int,  v_total);
    v_usadas := coalesce((p ->> 'cintasUsadas')::int, 0);

    -- a soma das duas pilhas tem que bater com o total da regra
    if v_novas + v_usadas <> v_total then
        v_usadas := least(v_usadas, v_total);
        v_novas  := v_total - v_usadas;
    end if;

    insert into public.pedidos (
        id, numero, cliente, cidade, uf, endereco, veiculo, placa,
        motorista, data, horario, cavaletes, lonas, forros,
        cintas, cintas_novas, cintas_usadas,
        lacres_lona, lacres_forro, entregue, data_entrega,
        coleta_cavalete_pendente, coleta_lona_pendente,
        quem_coletou_cavalete, quem_coletou_lona
    ) values (
        coalesce(nullif(p ->> 'id', '')::bigint,
                 nextval(pg_get_serial_sequence('public.pedidos', 'id'))),
        btrim(p ->> 'numero'),
        btrim(p ->> 'cliente'),
        btrim(p ->> 'cidade'),
        upper(btrim(p ->> 'uf')),
        v_end,
        coalesce(nullif(p ->> 'veiculo', ''), 'BITRUCK'),
        upper(coalesce(nullif(btrim(p ->> 'placa'), ''), '---')),
        coalesce(nullif(btrim(p ->> 'motorista'), ''), '---'),
        coalesce(public._para_data(p ->> 'data'), current_date),
        public._para_hora(p ->> 'horario'),
        v_cav,
        v_lon,
        v_for,
        v_total,
        v_novas,
        v_usadas,
        public._para_text_array(p -> 'lacresLona'),
        public._para_text_array(p -> 'lacresForro'),
        coalesce((p ->> 'entregue')::boolean, false),
        public._para_data(p ->> 'dataEntrega'),
        coalesce((p ->> 'coletaCavaletePendente')::boolean, true),
        coalesce((p ->> 'coletaLonPendente')::boolean,
                 coalesce((p ->> 'coletaLonaPendente')::boolean, true)),
        nullif(btrim(p ->> 'quemColetouCavalete'), ''),
        nullif(btrim(p ->> 'quemColetouLona'), '')
    )
    returning id into v_id;

    -- carga excepcional fica registrada
    if v_cav > 2 then
        insert into public.historico (tipo, pedido, detalhes, obs, criado_por)
        values ('Carga Excepcional', btrim(p ->> 'numero'),
                format('%s cavaletes, %s lonas, %s forros, %s cintas',
                       v_cav, v_lon, v_for, v_total),
                'Mais de 2 cavaletes (bitrem / carreta maior)',
                auth.uid());
    end if;

    return v_id;
end;
$$;

grant execute on function public.criar_pedido(jsonb) to authenticated;

