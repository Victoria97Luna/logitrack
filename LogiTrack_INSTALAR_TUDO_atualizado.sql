-- ---------------------------------------------------------------------
-- 5. CRIAR PEDIDO aceita cintasNovas / cintasUsadas
-- ---------------------------------------------------------------------
create or replace function public.criar_pedido(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id     bigint;
    v_novas  int;
    v_usadas int;
    v_total  int;
begin
    perform public._exigir_admin();

    if coalesce(btrim(p ->> 'numero'), '') = '' then
        raise exception 'O número do pedido é obrigatório.' using errcode = '23502';
    end if;
    if coalesce(btrim(p ->> 'cliente'), '') = '' then
        raise exception 'O cliente é obrigatório.' using errcode = '23502';
    end if;

    -- compatibilidade: se vier só "cintas", entra como nova
    v_total  := coalesce((p ->> 'cintas')::int, 4);
    v_novas  := coalesce((p ->> 'cintasNovas')::int,  v_total);
    v_usadas := coalesce((p ->> 'cintasUsadas')::int, 0);

    if v_novas = 0 and v_usadas = 0 and p ? 'cintasNovas' then
        v_total := 0;
    end if;

    insert into public.pedidos (
        id, numero, cliente, cidade, uf, endereco, veiculo, placa,
        motorista, data, horario, cavaletes, lonas, forros,
        cintas, cintas_novas, cintas_usadas,
        lacres_lona, lacres_forro, entregue, data_entrega,
        coleta_cavalete_pendente, coleta_lona_pendente,
        quem_coletou_cavalete, quem_coletou_lona
    ) values (
        coalesce(nullif(p ->> 'id', '')::bigint,
                 nextval(pg_get_serial_sequence('public.pedidos', 'id'))),
        btrim(p ->> 'numero'),
        btrim(p ->> 'cliente'),
        coalesce(nullif(btrim(p ->> 'cidade'), ''), '---'),
        upper(coalesce(nullif(btrim(p ->> 'uf'), ''), 'SP')),
        nullif(btrim(p ->> 'endereco'), ''),
        coalesce(nullif(p ->> 'veiculo', ''), 'BITRUCK'),
        upper(coalesce(nullif(btrim(p ->> 'placa'), ''), '---')),
        coalesce(nullif(btrim(p ->> 'motorista'), ''), '---'),
        coalesce(public._para_data(p ->> 'data'), current_date),
        public._para_hora(p ->> 'horario'),
        coalesce((p ->> 'cavaletes')::int, 1),
        coalesce((p ->> 'lonas')::int, 1),
        coalesce((p ->> 'forros')::int, 1),
        v_novas + v_usadas,
        v_novas,
        v_usadas,
        public._para_text_array(p -> 'lacresLona'),
        public._para_text_array(p -> 'lacresForro'),
        coalesce((p ->> 'entregue')::boolean, false),
        public._para_data(p ->> 'dataEntrega'),
        coalesce((p ->> 'coletaCavaletePendente')::boolean, true),
        coalesce((p ->> 'coletaLonaPendente')::boolean, true),
        nullif(btrim(p ->> 'quemColetouCavalete'), ''),
        nullif(btrim(p ->> 'quemColetouLona'), '')
    )
    returning id into v_id;

    return v_id;
end;
$$;

grant execute on function public.criar_pedido(jsonb) to authenticated;

-- ---------------------------------------------------------------------
-- 6. EDITAR PEDIDO aceita cintasNovas / cintasUsadas
-- ---------------------------------------------------------------------
create or replace function public.editar_pedido(p_id bigint, p jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_antes public.pedidos;
    v_resp  text;
    v_lacre record;
    v_novos_lona  text[];
    v_novos_forro text[];
begin
    perform public._exigir_admin();

    select * into v_antes from public.pedidos where id = p_id;
    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    select nome into v_resp from public.profiles where id = auth.uid();
    v_resp := coalesce(v_resp, 'Administrador');

    v_novos_lona  := case when p ? 'lacresLona'  then public._para_text_array(p -> 'lacresLona')  else v_antes.lacres_lona  end;
    v_novos_forro := case when p ? 'lacresForro' then public._para_text_array(p -> 'lacresForro') else v_antes.lacres_forro end;

    update public.pedidos
       set numero      = coalesce(nullif(btrim(p ->> 'numero'), ''), numero),
           cliente     = coalesce(nullif(btrim(p ->> 'cliente'), ''), cliente),
           cidade      = coalesce(nullif(btrim(p ->> 'cidade'), ''), cidade),
           uf          = upper(coalesce(nullif(btrim(p ->> 'uf'), ''), uf)),
           endereco    = coalesce(nullif(btrim(p ->> 'endereco'), ''), endereco),
           veiculo     = coalesce(nullif(p ->> 'veiculo', ''), veiculo),
           placa       = upper(coalesce(nullif(btrim(p ->> 'placa'), ''), placa)),
           motorista   = coalesce(nullif(btrim(p ->> 'motorista'), ''), motorista),
           data        = coalesce(public._para_data(p ->> 'data'), data),
           horario     = coalesce(public._para_hora(p ->> 'horario'), horario),
           cavaletes   = coalesce((p ->> 'cavaletes')::int, cavaletes),
           lonas       = coalesce((p ->> 'lonas')::int, lonas),
           forros      = coalesce((p ->> 'forros')::int, forros),
           cintas_novas  = coalesce((p ->> 'cintasNovas')::int,  cintas_novas),
           cintas_usadas = coalesce((p ->> 'cintasUsadas')::int, cintas_usadas),
           lacres_lona  = v_novos_lona,
           lacres_forro = v_novos_forro,
           atualizado_em = now()
     where id = p_id;

    if p ? 'lacresLona' or p ? 'lacresForro' then
        for v_lacre in
            select lacre, material from public.estoque_lacres
             where pedido_id = p_id
               and (
                    (material = 'Lona 8x7'  and lacre <> all (v_novos_lona))
                 or (material = 'Forro 5x3' and lacre <> all (v_novos_forro))
               )
        loop
            insert into public.lacre_eventos
                (lacre, tipo, pedido_numero, cliente, placa, responsavel, detalhes)
            values (
                v_lacre.lacre, 'Devolução ao Estoque',
                v_antes.numero, v_antes.cliente, v_antes.placa, v_resp,
                'Retirado do pedido ' || v_antes.numero || ' (' || v_antes.cliente ||
                ') na edição feita por ' || v_resp || '.'
            );

            update public.estoque_lacres
               set situacao = 'Nova / Estoque',
                   status   = 'Disponível no Galpão',
                   placa    = '---',
                   pedido_id = null
             where pedido_id = p_id and lacre = v_lacre.lacre and material = v_lacre.material;
        end loop;

        insert into public.estoque_lacres (material, lacre, situacao, status, placa, data, pedido_id)
        select 'Lona 8x7', l, 'Uso', 'Em trânsito',
               upper(coalesce(nullif(btrim(p ->> 'placa'), ''), v_antes.placa)),
               coalesce(public._para_data(p ->> 'data'), v_antes.data), p_id
          from unnest(v_novos_lona) as l
         where not exists (
             select 1 from public.estoque_lacres e
              where e.pedido_id = p_id and e.material = 'Lona 8x7' and e.lacre = l)
        union all
        select 'Forro 5x3', f, 'Uso', 'Em trânsito',
               upper(coalesce(nullif(btrim(p ->> 'placa'), ''), v_antes.placa)),
               coalesce(public._para_data(p ->> 'data'), v_antes.data), p_id
          from unnest(v_novos_forro) as f
         where not exists (
             select 1 from public.estoque_lacres e
              where e.pedido_id = p_id and e.material = 'Forro 5x3' and e.lacre = f);
    end if;

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (now(), 'Edição de Pedido', v_antes.numero,
            'Pedido alterado pela equipe', v_antes.placa,
            'Alteração registrada por ' || v_resp, auth.uid());
end;
$$;

grant execute on function public.editar_pedido(bigint, jsonb) to authenticated;

-- ---------------------------------------------------------------------
-- 7. AJUSTE MANUAL DO ESTOQUE DE CINTAS
-- ---------------------------------------------------------------------
-- Usado na contagem inicial e em qualquer correção de inventário.
-- Define o valor absoluto (não soma).

create or replace function public.ajustar_cintas(
    p_condicao text,
    p_quantidade int,
    p_motivo text default null
) returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_atual int;
    v_delta int;
begin
    perform public._exigir_admin();

    if p_condicao not in ('Nova', 'Usada') then
        raise exception 'Condição inválida: %', p_condicao using errcode = '22023';
    end if;
    if p_quantidade < 0 then
        raise exception 'A quantidade não pode ser negativa.' using errcode = '22003';
    end if;

    select quantidade into v_atual from public.cintas_saldo where condicao = p_condicao;
    v_atual := coalesce(v_atual, 0);
    v_delta := p_quantidade - v_atual;

    if v_delta <> 0 then
        perform public._mov_cintas(p_condicao, v_delta, 'Ajuste de Inventário',
            null, null, coalesce(p_motivo, 'Contagem de estoque'));
    end if;

    return p_quantidade;
end;
$$;

grant execute on function public.ajustar_cintas(text, integer, text) to authenticated;

