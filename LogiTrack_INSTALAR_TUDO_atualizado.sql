create or replace function public.excluir_pedido(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v        public.pedidos;
    v_resp   text;
    v_lacre  record;
begin
    perform public._exigir_admin();

    select * into v from public.pedidos where id = p_id;
    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    select nome into v_resp from public.profiles where id = auth.uid();
    v_resp := coalesce(v_resp, 'Administrador');

    -- Cada lacre volta para o galpão e ganha registro de devolução,
    -- dizendo para quem ele iria e quem excluiu o pedido.
    for v_lacre in
        select lacre, material from public.estoque_lacres where pedido_id = p_id
    loop
        insert into public.lacre_eventos
            (lacre, tipo, pedido_numero, cliente, placa, responsavel, detalhes)
        values (
            v_lacre.lacre,
            'Devolução ao Estoque',
            v.numero,
            v.cliente,
            v.placa,
            v_resp,
            'Estava destinado a ' || v.cliente || ' (pedido ' || v.numero ||
            ') e foi devolvido ao galpão porque ' || v_resp || ' excluiu o pedido.'
        );
    end loop;

    update public.estoque_lacres
       set situacao  = 'Nova / Estoque',
           status    = 'Disponível no Galpão',
           placa     = '---',
           pedido_id = null
     where pedido_id = p_id;

    delete from public.ordem_coleta_pedidos where pedido_id = p_id;
    delete from public.pedidos where id = p_id;

    insert into public.historico (data, tipo, pedido, detalhes, lacre_placa, obs, criado_por)
    values (now(), 'Exclusão de Pedido', v.numero,
            'Pedido excluído: ' || v.cliente || ' — lacres devolvidos ao estoque',
            v.placa,
            'Exclusão feita por ' || v_resp, auth.uid());
end;
$$;

