create or replace function public.editar_pedido(p_id bigint, p jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_antes public.pedidos;
    v_end   text;
    v_cav   int;
    v_regra jsonb;
begin
    perform public._exigir_admin();

    select * into v_antes from public.pedidos where id = p_id;
    if not found then
        raise exception 'Pedido % não encontrado.', p_id using errcode = 'P0002';
    end if;

    if p ? 'endereco' then
        v_end := btrim(coalesce(p ->> 'endereco', ''));
        if v_end = '' then
            raise exception 'O endereço não pode ficar em branco.' using errcode = '23502';
        end if;
        if length(v_end) < 10 then
            raise exception 'Endereço incompleto: informe rua, número e bairro.'
                using errcode = '22023';
        end if;
        if v_end !~ '[0-9]' then
            raise exception 'Falta o número do imóvel no endereço.' using errcode = '22023';
        end if;
    end if;

    -- se mexeram nos cavaletes, a proporção é refeita
    v_cav := coalesce((p ->> 'cavaletes')::int, v_antes.cavaletes);

    v_regra := public._normalizar_cavaletes(
        v_cav,
        coalesce((p ->> 'lonas')::int,  v_cav),
        coalesce((p ->> 'forros')::int, v_cav),
        null
    );

    update public.pedidos
       set numero      = coalesce(nullif(btrim(p ->> 'numero'), ''), numero),
           cliente     = coalesce(nullif(btrim(p ->> 'cliente'), ''), cliente),
           cidade      = coalesce(nullif(btrim(p ->> 'cidade'), ''), cidade),
           uf          = upper(coalesce(nullif(btrim(p ->> 'uf'), ''), uf)),
           endereco    = coalesce(nullif(btrim(p ->> 'endereco'), ''), endereco),
           veiculo     = coalesce(nullif(p ->> 'veiculo', ''), veiculo),
           placa       = upper(coalesce(nullif(btrim(p ->> 'placa'), ''), placa)),
           motorista   = coalesce(nullif(btrim(p ->> 'motorista'), ''), motorista),
           data        = coalesce(public._para_data(p ->> 'data'), data),
           horario     = coalesce(public._para_hora(p ->> 'horario'), horario),
           -- a proporção dos insumos sai dos cavaletes
           cavaletes   = (v_regra ->> 'cavaletes')::int,
           lonas       = (v_regra ->> 'lonas')::int,
           forros      = (v_regra ->> 'forros')::int,
           cintas_novas  = greatest(coalesce((p ->> 'cintasNovas')::int, cintas_novas),
                                    (v_regra ->> 'cintas')::int - coalesce(cintas_usadas, 0)),
           cintas_usadas = least(coalesce((p ->> 'cintasUsadas')::int, cintas_usadas),
                                 (v_regra ->> 'cintas')::int),
           lacres_lona  = case when p ? 'lacresLona'
                               then public._para_text_array(p -> 'lacresLona')
                               else lacres_lona end,
           lacres_forro = case when p ? 'lacresForro'
                               then public._para_text_array(p -> 'lacresForro')
                               else lacres_forro end,
           atualizado_em = now()
     where id = p_id;

    if v_cav > 2 and v_cav <> v_antes.cavaletes then
        insert into public.historico (tipo, pedido, detalhes, obs, criado_por)
        values ('Carga Excepcional', coalesce(p ->> 'numero', v_antes.numero),
                format('Alterado para %s cavaletes', v_cav),
                'Mais de 2 cavaletes (bitrem / carreta maior)',
                auth.uid());
    end if;
end;
$$;

