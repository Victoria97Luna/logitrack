);

comment on table public.profiles is
    'Perfil de acesso. papel = admin (equipe) ou motorista (portal).';

-- Cria o perfil automaticamente quando um usuário é criado no Auth.
create or replace function public.criar_perfil_do_usuario()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    insert into public.profiles (id, nome, papel, telefone)
    values (
        new.id,
        coalesce(nullif(new.raw_user_meta_data ->> 'nome', ''), split_part(new.email, '@', 1)),
        case when new.raw_user_meta_data ->> 'papel' = 'admin' then 'admin' else 'motorista' end,
        new.raw_user_meta_data ->> 'telefone'
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists trg_criar_perfil on auth.users;
create trigger trg_criar_perfil
    after insert on auth.users
    for each row execute function public.criar_perfil_do_usuario();

-- Impede que alguém promova a si mesmo a admin.
create or replace function public.proteger_papel_do_perfil()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if new.papel is distinct from old.papel and not public.eh_admin() then
        raise exception 'Somente um administrador pode alterar o papel de um usuário.'
            using errcode = '42501';
    end if;
    return new;
end;
$$;

