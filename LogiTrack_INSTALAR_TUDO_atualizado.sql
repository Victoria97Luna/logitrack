-- Converte 'DD/MM/YYYY' ou 'YYYY-MM-DD' em date. Vazio vira null.
create or replace function public._para_data(txt text)
returns date
language plpgsql
immutable
as $$
begin
    if txt is null or btrim(txt) = '' then
        return null;
    end if;
    if txt ~ '^\d{4}-\d{2}-\d{2}$' then
        return txt::date;
    end if;
    if txt ~ '^\d{2}/\d{2}/\d{4}$' then
        return to_date(txt, 'DD/MM/YYYY');
    end if;
    return null;
exception when others then
    return null;
end;
$$;

-- Converte 'HH:MM' em time. Vazio vira 08:00 (padrão do HTML).
create or replace function public._para_hora(txt text)
returns time
language plpgsql
immutable
as $$
begin
    if txt is null or btrim(txt) = '' then
        return time '08:00';
    end if;
    if txt ~ '^\d{2}:\d{2}(:\d{2})?$' then
        return txt::time;
    end if;
    return time '08:00';
exception when others then
    return time '08:00';
end;
$$;

-- Texto de array JSON -> text[], descartando vazios.
create or replace function public._para_text_array(j jsonb)
returns text[]
language sql
immutable
as $$
    select coalesce(
        array_agg(btrim(value) order by ord)
        filter (where btrim(coalesce(value, '')) <> ''),
        '{}'::text[]
    )
    from jsonb_array_elements_text(
             case when jsonb_typeof(j) = 'array' then j else '[]'::jsonb end
         ) with ordinality as t(value, ord);
$$;

