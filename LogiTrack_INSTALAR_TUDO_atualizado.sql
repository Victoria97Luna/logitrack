-- =====================================================================
-- LogiTrack — Script 12: confirmar a coleta parada por parada
--
-- Rode DEPOIS do script 11.
--
-- O motorista informa, em cada local, o que realmente recolheu. Pode ser
-- mais ou menos que o previsto. Se for diferente em qualquer item, o
-- sistema exige uma observação explicando o motivo.
--
-- A baixa nos pedidos é feita pelo que foi REALMENTE coletado:
--   • cavaletes  -> baixa total da coleta de cavaletes daquele cliente
--   • lonas/forros/cintas -> baixa da coleta de lonas daquele cliente
--   • cintas voltam para o estoque como USADAS (regra do script 05)
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Confirmar uma parada
-- ---------------------------------------------------------------------
create or replace function public.confirmar_parada_portal(
    p_token         uuid,
    p_item_id       bigint,
    p_cavaletes     integer,
    p_lonas         integer,
    p_forros        integer,
    p_cintas        integer,
    p_obs           text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem public.ordens_coleta;
    v_item  public.ordem_coleta_itens;
    v_dif   boolean;
begin
    select * into v_ordem
      from public.ordens_coleta
     where token = p_token
       and token_revogado = false
       and token_expira_em > now()
       for update;

    if not found then
        raise exception 'Link inválido, expirado ou revogado.' using errcode = '42501';
    end if;

    if v_ordem.status = 'Coletado no Local' then
        raise exception 'Esta coleta já foi confirmada.' using errcode = '23505';
    end if;

    select * into v_item
      from public.ordem_coleta_itens
     where id = p_item_id and ordem_id = v_ordem.id
       for update;

    if not found then
        raise exception 'Parada não encontrada nesta rota.' using errcode = 'P0002';
    end if;

    if p_cavaletes < 0 or p_lonas < 0 or p_forros < 0 or p_cintas < 0 then
        raise exception 'As quantidades não podem ser negativas.' using errcode = '22003';
    end if;

    -- Alguma quantidade diferente do previsto?
    v_dif := (p_cavaletes <> v_item.prev_cavaletes)
          or (p_lonas     <> v_item.prev_lonas)
          or (p_forros    <> v_item.prev_forros)
          or (p_cintas    <> v_item.prev_cintas);

    if v_dif and coalesce(btrim(p_obs), '') = '' then
        raise exception 'Explique por que a quantidade coletada em % foi diferente do previsto.',
                        v_item.cliente using errcode = '23502';
    end if;

    update public.ordem_coleta_itens
       set colet_cavaletes = p_cavaletes,
           colet_lonas     = p_lonas,
           colet_forros    = p_forros,
           colet_cintas    = p_cintas,
           obs_item        = nullif(btrim(coalesce(p_obs, '')), ''),
           conferido_em    = now()
     where id = p_item_id;

    return jsonb_build_object(
        'ok', true,
        'parada', v_item.parada,
        'cliente', v_item.cliente,
        'diferenca', v_dif
    );
end;
$$;

grant execute on function public.confirmar_parada_portal(uuid, bigint, integer, integer, integer, integer, text)
    to anon, authenticated;

-- ---------------------------------------------------------------------
-- 2. Fechar a rota inteira (só depois de todas as paradas conferidas)
-- ---------------------------------------------------------------------
-- a versão antiga tinha outra assinatura (com os totais soltos);
-- precisa sair para não ficarem duas funções com o mesmo nome
drop function if exists public.confirmar_coleta_portal(uuid, integer, integer, integer, text, text);

create or replace function public.confirmar_coleta_portal(
    p_token   uuid,
    p_frota   text default null,
    p_obs     text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ordem   public.ordens_coleta;
    v_falta   int;
    v_frota   text;
    v_obs     text;
    v_item    record;
    v_t_cav   int := 0;
    v_t_lon   int := 0;
    v_t_for   int := 0;
    v_t_cin   int := 0;
begin
    select * into v_ordem
      from public.ordens_coleta
     where token = p_token
       and token_revogado = false
       and token_expira_em > now()
       for update;

    if not found then
        raise exception 'Link inválido, expirado ou revogado.' using errcode = '42501';
    end if;

    if v_ordem.status = 'Coletado no Local' then
        raise exception 'Esta coleta já foi confirmada.' using errcode = '23505';
    end if;

    select count(*) into v_falta
      from public.ordem_coleta_itens
     where ordem_id = v_ordem.id
       and conferido_em is null;

    if v_falta > 0 then
        raise exception 'Ainda falta conferir % parada(s) da rota.', v_falta
            using errcode = '23502';
    end if;

    v_frota := coalesce(nullif(btrim(coalesce(p_frota, '')), ''), v_ordem.frota);
    v_obs   := nullif(btrim(coalesce(p_obs, '')), '');

    for v_item in
        select * from public.ordem_coleta_itens
         where ordem_id = v_ordem.id order by parada
    loop
        v_t_cav := v_t_cav + v_item.colet_cavaletes;
        v_t_lon := v_t_lon + v_item.colet_lonas;
        v_t_for := v_t_for + v_item.colet_forros;
        v_t_cin := v_t_cin + v_item.colet_cintas;

        -- Baixa nos pedidos daquele cliente, pelo que foi realmente coletado.
        if v_item.pedido_id is not null then
            if v_item.colet_cavaletes > 0 or v_item.prev_cavaletes = 0 then
                update public.pedidos
                   set coleta_cavalete_pendente = false,
                       quem_coletou_cavalete = v_frota,
                       atualizado_em = now()
                 where id = v_item.pedido_id;
            end if;

            if v_item.colet_lonas > 0 or v_item.colet_forros > 0 or v_item.colet_cintas > 0
               or v_item.prev_lonas = 0 then
                update public.pedidos
                   set coleta_lona_pendente = false,
                       quem_coletou_lona = v_frota,
                       atualizado_em = now()
                 where id = v_item.pedido_id;
            end if;
        end if;

        -- Cintas recolhidas entram no estoque como USADAS.
        if v_item.colet_cintas > 0 then
            perform public._mov_cintas(
                'Usada', v_item.colet_cintas, 'Entrada de Coleta',
                v_ordem.codigo, v_item.cliente,
                'Cintas recolhidas na coleta do cliente ' || v_item.cliente
            );
        end if;
    end loop;

    update public.ordens_coleta
       set coletado_cavaletes = v_t_cav,
           coletado_kits      = greatest(v_t_lon, v_t_for),
           coletado_cintas    = v_t_cin,
           frota_preencheu    = v_frota,
           obs_frota          = v_obs,
           status             = 'Coletado no Local',
           data_conclusao     = now()
     where id = v_ordem.id
    returning * into v_ordem;

    insert into public.historico (data, tipo, pedido, detalhes, obs, criado_por)
    values (now(), 'Coleta Realizada', v_ordem.codigo,
            format('Frota %s — %s cavalete(s), %s lona(s), %s forro(s), %s cinta(s)',
                   v_frota, v_t_cav, v_t_lon, v_t_for, v_t_cin),
            v_obs, null);

    perform public._auditar(
        'Confirmou coleta no portal',
        'Ordem ' || v_ordem.codigo,
        jsonb_build_object('frota', v_frota, 'cavaletes', v_t_cav,
