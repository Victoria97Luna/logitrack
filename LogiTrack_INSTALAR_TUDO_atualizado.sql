    insert into public.profiles (id, nome, papel, telefone)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'nome', split_part(new.email, '@', 1)),
        v_papel,
        new.raw_user_meta_data ->> 'telefone'
    )
    on conflict (id) do nothing;

    return new;
end;
$$;

