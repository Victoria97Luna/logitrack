-- ---------------------------------------------------------------------
-- 3. FUNÇÃO DE MOVIMENTAÇÃO
-- ---------------------------------------------------------------------
create or replace function public._mov_cintas(
    p_condicao  text,
    p_qtd       int,
    p_tipo      text,
    p_pedido    text default null,
    p_cliente   text default null,
    p_detalhes  text default null
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_saldo int;
    v_resp  text;
begin
    if p_qtd = 0 then
        return;
    end if;

    select nome into v_resp from public.profiles where id = auth.uid();

    insert into public.cintas_saldo (condicao, quantidade, atualizado_em)
    values (p_condicao, p_qtd, now())
    on conflict (condicao) do update
        set quantidade = public.cintas_saldo.quantidade + p_qtd,
            atualizado_em = now()
    returning quantidade into v_saldo;

    insert into public.cintas_movimentos
        (condicao, tipo, quantidade, saldo_depois, pedido_numero, cliente, responsavel, detalhes)
    values (
        p_condicao, p_tipo, p_qtd, v_saldo, p_pedido, p_cliente,
        coalesce(v_resp, 'Sistema'), p_detalhes
    );
end;
$$;

-- ---------------------------------------------------------------------
-- 4. TRIGGERS DO PEDIDO (saída, devolução, ajuste)
-- ---------------------------------------------------------------------

-- Ao criar: as cintas saem do saldo, na condição informada.
create or replace function public.ao_criar_pedido_cintas()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if new.cintas_novas > 0 then
        perform public._mov_cintas('Nova', -new.cintas_novas, 'Saída para Carga',
            new.numero, new.cliente, 'Cintas novas aplicadas na carga ' || new.placa);
    end if;
    if new.cintas_usadas > 0 then
        perform public._mov_cintas('Usada', -new.cintas_usadas, 'Saída para Carga',
            new.numero, new.cliente, 'Cintas usadas aplicadas na carga ' || new.placa);
    end if;
    return new;
end;
$$;

drop trigger if exists trg_criar_pedido_cintas on public.pedidos;
create trigger trg_criar_pedido_cintas
    after insert on public.pedidos
    for each row execute function public.ao_criar_pedido_cintas();

-- Ao editar: só movimenta a diferença.
create or replace function public.ao_editar_pedido_cintas()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    d_novas  int := coalesce(new.cintas_novas, 0)  - coalesce(old.cintas_novas, 0);
    d_usadas int := coalesce(new.cintas_usadas, 0) - coalesce(old.cintas_usadas, 0);
begin
    if d_novas <> 0 then
        perform public._mov_cintas('Nova',
            case when d_novas > 0 then -d_novas else -d_novas end,
            case when d_novas > 0 then 'Saída para Carga' else 'Devolução ao Estoque' end,
            new.numero, new.cliente,
            'Ajuste na edição do pedido ' || new.numero);
    end if;
    if d_usadas <> 0 then
        perform public._mov_cintas('Usada',
            case when d_usadas > 0 then -d_usadas else -d_usadas end,
            case when d_usadas > 0 then 'Saída para Carga' else 'Devolução ao Estoque' end,
            new.numero, new.cliente,
            'Ajuste na edição do pedido ' || new.numero);
    end if;
    return new;
end;
$$;

drop trigger if exists trg_editar_pedido_cintas on public.pedidos;
create trigger trg_editar_pedido_cintas
