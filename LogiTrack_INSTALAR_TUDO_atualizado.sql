-- 6. BUSCA DE LACRE com linha do tempo
-- ---------------------------------------------------------------------
create or replace function public.buscar_lacre(p_termo text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_termo text := btrim(replace(coalesce(p_termo, ''), '#', ''));
    v_estoque jsonb;
    v_pedidos jsonb;
    v_eventos jsonb;
begin
    perform public._exigir_admin();

    if v_termo = '' then
        return jsonb_build_object('termo', '', 'encontrado', false);
    end if;

    select coalesce(jsonb_agg(jsonb_build_object(
               'material', e.material,
               'situacao', e.situacao,
               'status', e.status,
               'placa', e.placa,
               'data', to_char(e.data, 'DD/MM/YYYY')
           ) order by e.id desc), '[]'::jsonb)
      into v_estoque
      from public.estoque_lacres e
     where e.lacre = v_termo;

    select coalesce(jsonb_agg(jsonb_build_object(
               'numero', p.numero,
               'cliente', p.cliente,
               'cidade', p.cidade,
               'uf', p.uf,
               'placa', p.placa,
               'motorista', p.motorista
           )), '[]'::jsonb)
      into v_pedidos
      from public.pedidos p
     where v_termo = any (p.lacres_lona) or v_termo = any (p.lacres_forro);

    select coalesce(jsonb_agg(jsonb_build_object(
               'tipo', ev.tipo,
               'pedido', ev.pedido_numero,
               'cliente', ev.cliente,
               'responsavel', ev.responsavel,
               'detalhes', ev.detalhes,
               'data', to_char(ev.criado_em, 'DD/MM/YYYY HH24:MI')
           ) order by ev.criado_em desc), '[]'::jsonb)
      into v_eventos
      from public.lacre_eventos ev
     where ev.lacre = v_termo;

    return jsonb_build_object(
        'termo', v_termo,
        'estoque', v_estoque,
        'pedidos', v_pedidos,
        'eventos', v_eventos,
        'encontrado',
            (jsonb_array_length(v_estoque) + jsonb_array_length(v_pedidos) + jsonb_array_length(v_eventos)) > 0
    );
end;
$$;

grant execute on function public.buscar_lacre(text) to authenticated;

-- ---------------------------------------------------------------------
-- 7. Preenche o histórico dos lacres que já existem hoje
-- ---------------------------------------------------------------------
-- Roda uma vez para que os lacres antigos também tenham início de
-- linha do tempo. Pode rodar de novo: não duplica.

create or replace function public.backfill_lacre_eventos()
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_total int := 0;
    v       record;
begin
    perform public._exigir_admin();

    for v in
        select e.lacre, e.material, e.situacao, e.placa, e.data,
               p.numero, p.cliente
          from public.estoque_lacres e
          left join public.pedidos p on p.id = e.pedido_id
    loop
        if not exists (
            select 1 from public.lacre_eventos ev
             where ev.lacre = v.lacre and ev.tipo =
                   case when v.situacao = 'Uso' then 'Saída para Carga' else 'Entrada no Estoque' end
               and coalesce(ev.pedido_numero, '') = coalesce(v.numero, '')
        ) then
            insert into public.lacre_eventos (lacre, tipo, pedido_numero, cliente, placa, responsavel, detalhes, criado_em)
            values (
                v.lacre,
                case when v.situacao = 'Uso' then 'Saída para Carga' else 'Entrada no Estoque' end,
                v.numero, v.cliente, v.placa, 'Sistema',
                'Registro importado do sistema anterior',
                (v.data + time '08:00')::timestamptz
            );
            v_total := v_total + 1;
        end if;
    end loop;

    return v_total;
end;
$$;

