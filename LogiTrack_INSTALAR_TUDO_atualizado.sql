                'id', l.id,
                'material', l.material,
                'lacre', l.lacre,
                'situacao', l.situacao,
                'status', l.status,
                'placa', l.placa,
                'data', to_char(l.data, 'YYYY-MM-DD')
            ) order by l.id desc)
            from public.estoque_lacres l
        ), '[]'::jsonb),

        'historico', coalesce((
            select jsonb_agg(jsonb_build_object(
                'data', to_char(h.data, 'YYYY-MM-DD HH24:MI'),
                'tipo', h.tipo,
                'pedido', h.pedido,
                'detalhes', h.detalhes,
                'lacrePlaca', h.lacre_placa,
                'obs', h.obs
            ) order by h.data desc)
            from public.historico h
        ), '[]'::jsonb)
    ) into v;

    return v;
end;
$$;

